/** SVG plate for a category, drawn in currentColor. */
export function plate(category) {
  const shapes = PLATES[category] || PLATES.art;
  return `<svg viewBox="0 0 64 64" fill="none" stroke="currentColor" stroke-width="1.6"
    stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${shapes}</svg>`;
}

